"""Единицы и масштабы, общие для всей модели.

Внутри решения скорость — м/с, время — наносекунды (как метки ROS), путь — метры.
Уравнение движения считается в безразмерных величинах: скорость в долях V_REF, время в долях T_REF.
"""

NS_PER_S = 1_000_000_000
KMH_PER_MPS = 3.6

G = 9.81                          # ускорение свободного падения, м/с²
V_REF = 15.0                      # масштаб скорости, м/с (наибольшая скорость в записях — 14,88)
T_REF = V_REF / G                 # масштаб времени, с: за T_REF сила «1 вес» разгоняет вагон до V_REF
L_REF = V_REF ** 2 / G            # масштаб длины, м

MAX_HANDLE_NOTCH = 15             # крайнее положение ручки контроллера (±15)


def seconds_to_ns(seconds: float) -> int:
    return int(seconds * NS_PER_S)
